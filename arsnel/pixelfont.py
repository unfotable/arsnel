GLYPHS: dict[str, tuple[str, ...]] = {
    ch: tuple(raw.split("/")) for ch, raw in _RAW.items()
}


def glyph(char: str) -> tuple[str, ...]:
    """Return the 7 rows of ``char`` (unknown characters render as ``?``)."""
    return GLYPHS.get(char.upper(), GLYPHS["?"])


def text_bitmap(text: str, spacing: int = 1) -> list[str]:
    """Render ``text`` to a list of 7 strings made of ``#`` and ``.``."""
    rows = [""] * GLYPH_H
    for index, char in enumerate(text):
        g = glyph(char)
        gap = "." * spacing if index else ""
        for y in range(GLYPH_H):
            rows[y] += gap + g[y]
    return rows


def text_width(text: str, spacing: int = 1) -> int:
    """Width in pixels of ``text`` rendered by :func:`text_bitmap`."""
    if not text:
        return 0
    return len(text) * GLYPH_W + (len(text) - 1) * spacing


def bitmap_to_blocks(rows: list[str], on: str = "██", off: str = "  ") -> list[str]:
    """Convert a ``#``/``.`` bitmap to block characters (2 columns per pixel)."""
    return ["".join(on if c == "#" else off for c in row).rstrip() for row in rows]
