"""Generate module READMEs, exercise stubs and quiz runners from Python content.

Source of truth per module:

* ``content/module_NN.py``                  prose, quiz, metadata
* ``curriculum/<module>/examples/*.py``     hand-written runnable examples
* ``curriculum/<module>/solutions/ex_*.py`` hand-written solutions

Generated (never edit by hand): ``README.md``, ``exercises/ex_*.py``, ``quiz.py``.
Run ``python generate.py`` to refresh, ``python generate.py --check`` to detect drift.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

from arsnel.ascii_art import box
from arsnel.manifest import MODULES, get_module
from arsnel.models import ModuleContent, ModuleMeta
from arsnel.paths import CURRICULUM

SOLUTION_START = re.compile(r"^(\s*)# --- solution ---\s*$")
SOLUTION_END = re.compile(r"^\s*# --- end ---\s*$")
REQUIRES = re.compile(r"^#\s*requires:\s*(.+)$", re.MULTILINE)
GENERATED = (
    "<!-- GENERATED by generate.py from content/module_{mid}.py - DO NOT EDIT -->"
)
XP_EXERCISE = 10
XP_QUIZ = 20


class ScaffoldError(RuntimeError):
    """Raised when module sources are inconsistent."""


def required_modules(source: str) -> list[str]:
    """Return third-party modules declared by a ``# requires: a, b`` header."""
    found = REQUIRES.search(source[:600])
    if not found:
        return []
    return [name.strip() for name in found.group(1).split(",") if name.strip()]


def derive_stub(source: str, name: str) -> str:
    """Turn a solution file into an exercise stub.

    Every block between ``# --- solution ---`` and ``# --- end ---`` (indented,
    i.e. inside a function or method) is replaced by ``raise NotImplementedError``.
    """
    out: list[str] = []
    skipping = False
    regions = 0
    for number, line in enumerate(source.splitlines(), start=1):
        start = SOLUTION_START.match(line)
        if skipping:
            if SOLUTION_END.match(line):
                skipping = False
            elif start:
                raise ScaffoldError(f"{name}:{number}: nested solution marker")
            continue
        if start:
            indent = start.group(1)
            if not indent:
                raise ScaffoldError(
                    f"{name}:{number}: solution marker must be indented"
                )
            out.append(f'{indent}raise NotImplementedError("TODO: your turn")')
            skipping = True
            regions += 1
            continue
        if SOLUTION_END.match(line):
            raise ScaffoldError(f"{name}:{number}: '# --- end ---' without a start")
        out.append(line)
    if skipping:
        raise ScaffoldError(f"{name}: unterminated solution region")
    if regions == 0:
        raise ScaffoldError(f"{name}: no '# --- solution ---' region found")
    text = "\n".join(out) + "\n"
    if "# TODO" not in text:
        raise ScaffoldError(f"{name}: stub has no '# TODO' comment")
    return text


def render_quiz_py(meta: ModuleMeta) -> str:
    """Source of the thin ``quiz.py`` runner for ``meta``."""
    return f'''"""ARSNEL > {meta.prompt} quiz.  Run:  python quiz.py"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from arsnel.manifest import get_module
from arsnel.quizlib import run_quiz
from content.module_{meta.mid} import CONTENT

if __name__ == "__main__":
    raise SystemExit(run_quiz(get_module({meta.number}), CONTENT.quiz))
'''


def capture_output(path: Path, limit: int = 40) -> str:
    """Run an example and return its (truncated) stdout."""
    env = {**os.environ, "PYTHONHASHSEED": "0", "PYTHONDONTWRITEBYTECODE": "1"}
    proc = subprocess.run(
        [sys.executable, path.name],
        cwd=path.parent,
        env=env,
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )
    if proc.returncode != 0:
        raise ScaffoldError(f"{path}: exited {proc.returncode}\n{proc.stderr[-800:]}")
    lines = [line.rstrip() for line in proc.stdout.rstrip().splitlines()]
    if len(lines) > limit:
        lines = [*lines[:limit], f"... ({len(lines) - limit} more lines)"]
    return "\n".join(lines)


def _module_dir(meta: ModuleMeta, root: Path) -> Path:
    return root / meta.dirname


def _check_files(meta: ModuleMeta, content: ModuleContent, root: Path) -> None:
    """Make sure every referenced file exists and nothing is undocumented."""
    base = _module_dir(meta, root)
    listed_examples = {e.file for e in content.examples}
    listed_solutions = {e.file for e in content.exercises}
    for name in listed_examples:
        if not (base / "examples" / name).is_file():
            raise ScaffoldError(f"{meta.prompt}: missing examples/{name}")
    for name in listed_solutions:
        if not (base / "solutions" / name).is_file():
            raise ScaffoldError(f"{meta.prompt}: missing solutions/{name}")
    for folder, listed in (
        ("examples", listed_examples),
        ("solutions", listed_solutions),
    ):
        on_disk = {p.name for p in (base / folder).glob("*.py")}
        extra = on_disk - listed
        if extra:
            raise ScaffoldError(
                f"{meta.prompt}: {folder}/ has unlisted files {sorted(extra)}"
            )


def _nav(meta: ModuleMeta) -> str:
    links: list[str] = []
    if meta.number > 0:
        prev = get_module(meta.number - 1)
        links.append(f"[< {prev.prompt}](../{prev.dirname}/README.md)")
    if meta.number < len(MODULES) - 1:
        nxt = get_module(meta.number + 1)
        links.append(f"[{nxt.prompt} >](../{nxt.dirname}/README.md)")
    return "  |  ".join(["[ARSNEL home](../../README.md)", *links])


def render_readme(
    meta: ModuleMeta, content: ModuleContent, root: Path, with_output: bool = True
) -> str:
    """Render a module README (Markdown) from its content."""
    base = _module_dir(meta, root)
    xp = len(content.exercises) * XP_EXERCISE + XP_QUIZ
    prereq = ", ".join(f"module_{p:02d}" for p in meta.prerequisites) or "none"
    header = box(
        [meta.title.upper(), f"{meta.level}  |  ~{meta.est_hours:g}h  |  {xp} XP"],
        title=f"> {meta.prompt}",
    )
    parts: list[str] = [
        GENERATED.format(mid=meta.mid),
        "",
        f"# ARSNEL / {meta.prompt} - {meta.title}",
        "",
        "```text",
        header,
        "```",
        "",
        f"> {meta.tagline}",
        "",
        f"**Level:** {meta.level} | **Time:** ~{meta.est_hours:g}h | **XP:** {xp} | "
        f"**Requires:** {prereq}",
        "",
        content.intro.strip(),
        "",
    ]
    for index, lesson in enumerate(content.lessons, start=1):
        parts += [
            f"## > lesson_{index:02d}: {lesson.title}",
            "",
            lesson.body.strip(),
            "",
        ]

    parts += [
        "## $ python examples/",
        "",
        "Run any example from this folder:",
        "",
        "```bash",
        f"cd curriculum/{meta.dirname}",
        "python examples/<file>.py",
        "```",
        "",
    ]
    extras: list[str] = []
    for example in content.examples:
        path = base / "examples" / example.file
        source = path.read_text(encoding="utf-8")
        extras += [m for m in required_modules(source) if m not in extras]
        parts += [
            f"### {example.title}",
            "",
            example.blurb.strip(),
            "",
            "```python",
            f"# examples/{example.file}",
            source.rstrip(),
            "```",
            "",
        ]
        if example.show_output and with_output:
            parts += [
                "Output:",
                "",
                "```text",
                f"$ python examples/{example.file}",
                capture_output(path),
                "```",
                "",
            ]
    if extras:
        parts += [
            f"> Extra packages used here: `{', '.join(extras)}` "
            '(install with `pip install -e ".[all]"`).',
            "",
        ]

    parts += [
        "## > exercises",
        "",
        "Open a file in `exercises/`, replace each `# TODO`, then run it:",
        "",
        "```bash",
        "python exercises/<file>.py   # prints PASS when you are done",
        "```",
        "",
        "| file | task | difficulty |",
        "| --- | --- | --- |",
    ]
    for exercise in content.exercises:
        stars = "★" * exercise.difficulty + "☆" * (3 - exercise.difficulty)
        parts.append(
            f"| [`{exercise.file}`](exercises/{exercise.file}) | "
            f"**{exercise.title}** - {exercise.brief} | {stars} |"
        )
    parts += [
        "",
        "Stuck? Compare with `solutions/` *after* you have tried.",
        "",
        "## > quiz",
        "",
        "```bash",
        "python quiz.py",
        "```",
        "",
        f"{len(content.quiz)} questions, pass mark 70%. Scores are saved to "
        "`.arsnel/quiz_results.json` and count toward your XP.",
        "",
    ]
    if content.cheatsheet:
        parts += (
            ["## > cheatsheet", ""]
            + [f"- {item}" for item in content.cheatsheet]
            + [""]
        )
    if content.next_steps.strip():
        parts += ["## > next", "", content.next_steps.strip(), ""]
    parts += ["---", _nav(meta), ""]
    return "\n".join(parts)


def expected_files(
    meta: ModuleMeta, content: ModuleContent, root: Path, with_output: bool = True
) -> dict[Path, str]:
    """Return ``{path: text}`` for every generated file of a module."""
    _check_files(meta, content, root)
    base = _module_dir(meta, root)
    files: dict[Path, str] = {
        base / "README.md": render_readme(meta, content, root, with_output),
        base / "quiz.py": render_quiz_py(meta),
    }
    for exercise in content.exercises:
        source = (base / "solutions" / exercise.file).read_text(encoding="utf-8")
        files[base / "exercises" / exercise.file] = derive_stub(
            source, f"{meta.prompt}/{exercise.file}"
        )
    return files


def generate(
    root: Path = CURRICULUM,
    only: int | None = None,
    check: bool = False,
    with_output: bool = True,
) -> list[Path]:
    """Write (or, with ``check``, only compare) generated files.

    Returns the paths that were changed (or that drifted).
    """
    from content import all_content

    changed: list[Path] = []
    for number, content in sorted(all_content().items()):
        if only is not None and number != only:
            continue
        meta = get_module(number)
        for path, text in expected_files(meta, content, root, with_output).items():
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != text:
                changed.append(path)
                if not check:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(text, encoding="utf-8")
    return changed
