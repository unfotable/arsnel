JS = """\
/* ARSNEL site behaviour: theme toggle, module search, copy buttons, terminal demo. */
(function () {
  "use strict";
  var root = document.documentElement;
  try {
    var saved = localStorage.getItem("arsnel-theme");
    if (saved) { root.setAttribute("data-theme", saved); }
  } catch (e) { /* storage may be blocked */ }

  var toggle = document.getElementById("theme-toggle");
  if (toggle) {
    toggle.addEventListener("click", function () {
      var dark = root.getAttribute("data-theme") === "dark" ||
        (!root.getAttribute("data-theme") &&
         window.matchMedia("(prefers-color-scheme: dark)").matches);
      var next = dark ? "light" : "dark";
      root.setAttribute("data-theme", next);
      try { localStorage.setItem("arsnel-theme", next); } catch (e) { /* ignore */ }
    });
  }

  document.querySelectorAll("button.copy").forEach(function (btn) {
    btn.addEventListener("click", function () {
      var code = btn.closest(".term").querySelector("code");
      var done = function () {
        btn.textContent = "copied";
        setTimeout(function () { btn.textContent = "copy"; }, 1200);
      };
      if (navigator.clipboard) {
        navigator.clipboard.writeText(code.textContent).then(done, function () {});
      }
    });
  });

  /* searchable module index (data is inlined in #search-data) */
  var box = document.getElementById("q");
  var dataNode = document.getElementById("search-data");
  if (box && dataNode) {
    var docs = JSON.parse(dataNode.textContent);
    var cards = Array.prototype.slice.call(document.querySelectorAll(".mod"));
    var empty = document.getElementById("empty");
    var run = function () {
      var terms = box.value.toLowerCase().split(/\\s+/).filter(Boolean);
      var shown = 0;
      cards.forEach(function (card) {
        var doc = docs[card.getAttribute("data-id")] || "";
        var hit = terms.every(function (t) { return doc.indexOf(t) !== -1; });
        card.classList.toggle("hidden", !hit);
        if (hit) { shown += 1; }
      });
      if (empty) { empty.classList.toggle("hidden", shown !== 0); }
    };
    box.addEventListener("input", run);
    document.addEventListener("keydown", function (ev) {
      if (ev.key === "/" && document.activeElement !== box) {
        ev.preventDefault();
        box.focus();
      }
    });
  }

  /* interactive terminal demo (outputs were captured from real runs at build time) */
  var screen = document.getElementById("demo-screen");
  var input = document.getElementById("demo-input");
  var dataEl = document.getElementById("demo-data");
  if (screen && input && dataEl) {
    var demo = JSON.parse(dataEl.textContent);
    var history = [];
    var pos = 0;
    var print = function (text) {
      screen.appendChild(document.createTextNode(text + "\\n"));
      screen.scrollTop = screen.scrollHeight;
    };
    print(demo.intro);
    var exec = function (line) {
      var cmd = line.trim();
      print(demo.prompt + " " + line);
      if (!cmd) { return; }
      history.push(cmd);
      pos = history.length;
      if (cmd === "clear") { screen.textContent = ""; return; }
      var out = demo.commands[cmd];
      print(out === undefined ? "arsnel: command not found: " + cmd +
        "  (try: help)" : out);
    };
    input.addEventListener("keydown", function (ev) {
      if (ev.key === "Enter") { exec(input.value); input.value = ""; }
      else if (ev.key === "ArrowUp" && pos > 0) {
        pos -= 1; input.value = history[pos]; ev.preventDefault();
      } else if (ev.key === "ArrowDown") {
        pos = Math.min(history.length, pos + 1);
        input.value = history[pos] || ""; ev.preventDefault();
      }
    });
    document.querySelectorAll(".chip").forEach(function (chip) {
      chip.addEventListener("click", function () {
        exec(chip.getAttribute("data-cmd"));
        input.focus();
      });
    });
  }
})();
"""
