"""README and static-site generation."""

from __future__ import annotations

import json
import re
from pathlib import Path

import build_readme
import build_site
from arsnel import NAME
from arsnel.manifest import MODULES
from arsnel.mdrender import render_markdown
from arsnel.progress_core import Snapshot


def test_readme_has_required_sections() -> None:
    text = build_readme.render(Snapshot(timestamp="t"))
    assert '<h1 align="center">ARSNEL</h1>' in text
    assert text.count("ARSNEL") >= 4
    assert "██" in text
    for heading in ("xp_status", "why_arsnel", "quickstart", "curriculum", "charts"):
        assert heading in text
    for meta in MODULES:
        assert meta.dirname in text
    for chart in ("roadmap", "big_o", "dependency_graph", "skill_radar"):
        assert f"assets/charts/{chart}.png" in text


def test_readme_on_disk_is_current() -> None:
    from arsnel.paths import README

    assert "GENERATED by build_readme.py" in README.read_text(encoding="utf-8")


def test_markdown_rendering_and_links() -> None:
    src = (
        "# T\n\n```python\nprint(1)\n```\n\n"
        "[home](../../README.md) [next](../module_02_control_flow/README.md) "
        "[ex](exercises/ex_01_greeting.py) [web](https://example.com)\n"
    )
    html = render_markdown(src, "module_01_syntax")
    assert 'class="term"' in html
    assert 'href="../index.html"' in html
    assert 'href="module_02_control_flow.html"' in html
    assert "blob/main/curriculum/module_01_syntax/exercises/ex_01_greeting.py" in html
    assert 'href="https://example.com"' in html


def test_site_builds(tmp_path: Path) -> None:
    out = tmp_path / "site"
    build_site.build(out, Snapshot(timestamp="t"))
    index = (out / "index.html").read_text(encoding="utf-8")
    assert "<title>ARSNEL" in index
    assert 'id="search-data"' in index
    assert 'id="demo-data"' in index
    assert (out / ".nojekyll").exists()
    pages = sorted((out / "modules").glob("*.html"))
    assert len(pages) == len(MODULES)
    assert (out / "charts.html").exists()
    css = (out / "static" / "arsnel.css").read_text(encoding="utf-8")
    assert "4px 4px 0" in css and "prefers-color-scheme: dark" in css
    assert "border-radius: 0" in css
    docs = json.loads((out / "search.json").read_text(encoding="utf-8"))
    assert set(docs) == {m.mid for m in MODULES}
    assert "decorator" in docs["10"]
    # every local href/src in the index resolves to a file
    for target in re.findall(r'(?:href|src)="([^"#:]+)"', index):
        assert (out / target).exists(), target


def test_demo_outputs_are_real() -> None:
    demo = build_site.demo_data(Snapshot(timestamp="t"))
    assert "Hello" in demo["commands"]["python hello_world.py"]
    assert NAME in demo["intro"].upper()
