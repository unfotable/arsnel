"""Generate README.md from Python (ASCII art, XP bar, tables, charts, badges).

Usage:  python build_readme.py            # uses .arsnel/progress.json if present
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from arsnel import NAME, TAGLINE
from arsnel.ascii_art import hero, mascot, xp_bar
from arsnel.badges import BADGES, badge_grid
from arsnel.langstats import MIN_PYTHON_PERCENT, python_percent
from arsnel.manifest import MODULES
from arsnel.paths import PROGRESS_FILE, README
from arsnel.progress_core import ModuleProgress, Snapshot, scan

CHARTS = (
    ("roadmap", "Learning-path roadmap"),
    ("dependency_graph", "Concept dependency graph"),
    ("big_o", "Big-O complexity"),
    ("skill_radar", "Skill radar"),
    ("progress_line", "Progress over time"),
    ("language_donut", "Repository languages"),
)

TREE = """\
ARSNEL/
├── README.md                 <- generated by build_readme.py
├── build_site.py             <- Python-only static site generator
├── progress.py               <- scans exercises -> XP, charts, README
├── generate.py               <- content/*.py -> READMEs, exercise stubs, quizzes
├── bootstrap.py              <- one-command setup
├── arsnel/                   <- engine: quiz, progress, pixel art, themes
├── content/                  <- every lesson, quiz question and blurb as Python data
├── curriculum/module_NN_*/   <- README.md, examples/, exercises/, solutions/, quiz.py
├── charts/                   <- six matplotlib chart scripts
├── assets/                   <- generated SVGs and PNG/SVG charts
├── tests/                    <- pytest suite (incl. the >=97% Python check)
└── .github/workflows/ci.yml  <- ruff, black, mypy, pytest, site, progress
"""


def snapshot_from_disk() -> Snapshot:
    """Load the saved progress snapshot, or an all-zero one (no code is run)."""
    if PROGRESS_FILE.exists():
        data: dict[str, Any] = json.loads(PROGRESS_FILE.read_text(encoding="utf-8"))
        snap = Snapshot(timestamp=str(data.get("timestamp", "")))
        snap.modules = [ModuleProgress(**m) for m in data.get("modules", [])]
        return snap
    return scan(run=False)


def html_tagline() -> str:
    """The tagline with Markdown backticks converted to <code> for raw HTML."""
    parts = TAGLINE.split("`")
    return "".join(
        f"<code>{part}</code>" if i % 2 else part for i, part in enumerate(parts)
    )


def _mini_bar(done: int, total: int, width: int = 10) -> str:
    filled = round(width * done / total) if total else 0
    return "█" * filled + "░" * (width - filled)


def module_table(snapshot: Snapshot) -> str:
    """Markdown table of all modules with per-module progress."""
    progress = {m.number: m for m in snapshot.modules}
    rows = [
        "| # | module | level | hours | exercises | XP |",
        "| ---: | --- | --- | ---: | --- | ---: |",
    ]
    for meta in MODULES:
        p = progress.get(meta.number)
        done, total = (p.done, p.total) if p else (0, 0)
        xp = p.max_xp if p else 0
        rows.append(
            f"| {meta.mid} | [{meta.title}](curriculum/{meta.dirname}/README.md) "
            f"| {meta.level.title()} | {meta.est_hours:g} "
            f"| `{_mini_bar(done, total)}` {done}/{total} | {xp} |"
        )
    return "\n".join(rows)


def render(snapshot: Snapshot) -> str:
    """Return the full README text."""
    level, rank = snapshot.level
    bar = xp_bar(snapshot.percent, 40)
    unlocked = sum(1 for b in BADGES if b.unlocked(snapshot.stats()))
    py = python_percent()
    lines = [
        "<!-- GENERATED by build_readme.py - edit the generator, not this file -->",
        f'<p align="center"><img src="assets/banner.svg" alt="{NAME}" width="100%"></p>',
        "",
        f'<h1 align="center">{NAME}</h1>',
        "",
        "```text",
        hero(),
        "```",
        "",
        f'<p align="center"><b>{html_tagline()}</b></p>',
        "",
        f'<p align="center"><code>{len(MODULES)} modules</code> · '
        f"<code>{snapshot.exercises_total} exercises</code> · "
        f"<code>{len(MODULES)} quizzes</code> · <code>{len(BADGES)} badges</code> · "
        f"<code>{py:.1f}% Python</code> · <code>MIT</code></p>",
        "",
        "## > xp_status",
        "",
        '<p align="center"><img src="assets/xp_bar.svg" alt="XP bar" width="100%"></p>',
        "",
        "```text",
        bar,
        f"LVL {level}  {rank}",
        f"XP {snapshot.xp}/{snapshot.max_xp}   exercises {snapshot.exercises_done}/"
        f"{snapshot.exercises_total}   quizzes {snapshot.quizzes_passed}/{len(MODULES)}"
        f"   badges {unlocked}/{len(BADGES)}",
        "```",
        "",
        "> Fresh clone = 0 XP. Solve an exercise, run `make progress`, and this bar "
        "(plus the charts below) updates - CI does the same on every push to your fork.",
        "",
        "## > why_arsnel",
        "",
        "- **Everything runs.** Every example, solution and exercise self-check is a real, "
        "typed, linted Python file. CI executes all of them.",
        "- **Learn by doing.** Each module: lesson README -> runnable `examples/` -> "
        "`exercises/` with `# TODO` stubs that grade themselves -> a terminal `quiz.py`.",
        "- **Measured progress.** XP, ranks and badges are computed from what you actually "
        "solved, not what you clicked.",
        "- **100% Python tooling.** The site, charts, ASCII art, quizzes and even this README "
        f"are generated by Python (>= {MIN_PYTHON_PERCENT:.0f}% of the repo, enforced by a test).",
        "- **Pixel/terminal aesthetic** because learning should feel like hacking the planet.",
        "",
        "## $ quickstart",
        "",
        "```bash",
        "git clone https://github.com/unfotable/arsnel && cd arsnel",
        "python bootstrap.py              # venv + deps + generated files (or: make setup)",
        "source .venv/bin/activate        # Windows: .venv\\Scripts\\activate",
        "cd curriculum/module_01_syntax",
        "python examples/hello_world.py",
        "python exercises/ex_01_greeting.py   # FAIL until you solve the TODO",
        "python quiz.py",
        "make progress                    # update XP bar, charts and README",
        "make site && python -m http.server -d site 8000",
        "```",
        "",
        "## > curriculum",
        "",
        module_table(snapshot),
        "",
        "## > charts",
        "",
    ]
    for name, title in CHARTS:
        lines += [f"### {title}", "", f"![{title}](assets/charts/{name}.png)", ""]
    lines += [
        "## > achievements",
        "",
        "```text",
        badge_grid(snapshot.stats()),
        "```",
        "",
        "## > mascot",
        "",
        "Meet **ARS**, the pixel snake who guards your progress bar:",
        "",
        "```text",
        mascot(),
        "```",
        "",
        "## > how_it_works",
        "",
        "```text",
        TREE.rstrip(),
        "```",
        "",
        "1. Authors edit `content/module_NN.py` (prose + quizzes) and hand-written "
        "`examples/` + `solutions/`.",
        "2. `python generate.py` renders module READMEs, derives the exercise stubs from the "
        "solutions (`# --- solution ---` regions) and writes `quiz.py`.",
        "3. `python progress.py` runs every exercise, awards XP and redraws charts.",
        "4. `python build_site.py` renders the Jinja2/Markdown static site into `site/`.",
        "",
        "## > contributing",
        "",
        "Read [CONTRIBUTING.md](CONTRIBUTING.md). Quality gate: `make check` "
        "(ruff, black, mypy, pytest, generator drift). Licensed under [MIT](LICENSE).",
        "",
        "```text",
        "$ exit 0 █",
        "```",
        "",
    ]
    return "\n".join(lines)


def write(snapshot: Snapshot | None = None, path: Path = README) -> Path:
    """Render and write the README; return its path."""
    path.write_text(render(snapshot or snapshot_from_disk()), encoding="utf-8")
    return path


if __name__ == "__main__":
    print("wrote", write())
